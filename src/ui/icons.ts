export type IconName = keyof typeof ICONS;

/** Icon names that may come from data (category files, the database). */
export const isIconName = (name: string): name is IconName => name in ICONS;

/** Every icon a category can use, for the admin panel's picker. */
export const ICON_NAMES = Object.keys(ICONS) as IconName[];

/**
 * An inline SVG icon. Decorative by default (hidden from screen readers);
 * pass `label` when the icon is the only content of a control.
 */
export function icon(
  name: IconName | string,
  { size, label, class: extra }: { size?: number; label?: string; class?: string } = {},
): SVGElement {
  const node = isIconName(name) ? ICONS[name] : ICONS['circle-help'];
  const el = createElement(node, {
    class: `icon${extra ? ` ${extra}` : ''}`,
    'stroke-width': 2,
    ...(size ? { width: size, height: size } : { width: '1em', height: '1em' }),
  });
  if (label) {
    el.setAttribute('role', 'img');
    el.setAttribute('aria-label', label);
  } else {
    el.setAttribute('aria-hidden', 'true');
  }
  return el;
}
